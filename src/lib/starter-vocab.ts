const ORDER: Category[] = ['Nouns', 'い-adjectives', 'な-adjectives', 'U-verbs', 'Ru-verbs', 'Irregular verbs', 'Adverbs and other expressions'];

export interface StarterWord {
  id: string;
  lesson: number;
  term: string;
  kana: string;
  meaning: string;
  category: string;
  position: number;
  starter: true;
}

export function starterWords(lesson: number): StarterWord[] {
  const l = STARTER[lesson];
  if (!l) return [];
  const out: StarterWord[] = [];
  for (const cat of ORDER)
    for (const [kana, kanji, meaning] of l[cat] ?? [])
      out.push({ id: `s-${lesson}-${out.length}`, lesson, term: kanji || kana, kana, meaning, category: cat, position: out.length, starter: true });
  return out;
}

export const starterTheme = (lesson: number) => STARTER[lesson]?.theme;
